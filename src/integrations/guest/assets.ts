import { readFile } from 'node:fs/promises';
import { posix } from 'node:path';

import { runBoundedIO } from '#operation';

import {
  AGENT_BIN,
  AGENT_HOME,
  AGENT_PATH,
  ENVIRONMENT_PATH,
  GUEST_ROOT,
  HOMEBREW_PATH,
  HOMEBREW_PREFIX,
  LINUXBREW_HOME,
  SESSION_DIRECTORY,
  SESSION_PATH,
  SYSTEM_PATH,
} from './layout.js';
import { quoteWord } from './session/framing.js';

import type { GuestAsset } from '#os/contracts';

/** the guest layout every guest program receives, as the variables its header assigns */
const LAYOUT_VARIABLES: Readonly<Record<string, string>> = {
  OA_GUEST_ROOT: GUEST_ROOT,
  OA_ENVIRONMENT_PATH: ENVIRONMENT_PATH,
  OA_AGENT_HOME: AGENT_HOME,
  OA_AGENT_BIN: AGENT_BIN,
  OA_AGENT_PATH: AGENT_PATH,
  OA_LINUXBREW_HOME: LINUXBREW_HOME,
  OA_HOMEBREW_PREFIX: HOMEBREW_PREFIX,
  OA_HOMEBREW_PATH: HOMEBREW_PATH,
  OA_SYSTEM_PATH: SYSTEM_PATH,
  OA_SESSION_PATH: SESSION_PATH,
  OA_SESSION_DIRECTORY: SESSION_DIRECTORY,
};

/**
 * declares a guest program installed under the guest root at the path it has
 * under the package's `guest` directory, so the guest tree mirrors it
 * @param path path of the `.sh` file relative to the package's `guest` directory
 * @param mode installed mode
 * @returns the guest program
 */
export function guestAsset(path: string, mode: GuestAsset['mode']): GuestAsset {
  assetUrl({ path });

  return { path, mode, installAs: `${GUEST_ROOT}/${path}` };
}

/**
 * locates a guest program in the package's `guest` directory, which sits at
 * the package root beside both `src` and `lib`, so one path resolves from this
 * module in both the source and the packed layout
 * @param asset the guest program
 * @returns URL of the `.sh` file
 * @throws {Error} when the path is not a plain relative path to a `.sh` file
 */
export function assetUrl(asset: Pick<GuestAsset, 'path'>): URL {
  const { path } = asset;
  if (
    posix.isAbsolute(path) ||
    posix.normalize(path) !== path ||
    path.split('/').some((segment) => segment === '' || segment === '..') ||
    !path.endsWith('.sh')
  ) {
    throw new Error(`Guest asset ${path} is not a plain relative .sh path`);
  }

  return new URL(`../../../guest/${path}`, import.meta.url);
}

/**
 * reads a guest program so setup can send it to the guest, with the guest
 * layout assigned right after its shebang, so the program never spells a
 * guest path itself
 * @param asset the guest program
 * @returns its contents behind the layout header
 */
export async function readAsset(
  asset: Pick<GuestAsset, 'path'>,
): Promise<string> {
  const url = assetUrl(asset);
  const source = await runBoundedIO(async () => readFile(url, 'utf8'));
  const shebang = /^#!.*\n/.exec(source)?.[0] ?? '';

  return [
    `${shebang}# generated by readAsset from src/integrations/guest/layout.ts`,
    ...Object.entries(LAYOUT_VARIABLES).map(
      ([name, value]) => `${name}=${quoteWord(value)}`,
    ),
    `# ---- guest/${asset.path} ----`,
    source.slice(shebang.length),
  ].join('\n');
}
